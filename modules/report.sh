#!/bin/bash

generate_report() {
    local target="$1"
    local outdir="$2"
    local report="$outdir/report.md"

    log "Generating report..."

    {
        echo "# Reconnaissance Report"
        echo
        echo "**Target:** \`$target\`"
        echo "**Date:** $(date)"
        echo "**Generated by:** Mobile Recon Framework"
        echo
        echo "---"
        echo
        echo "## DNS Records"
        echo '```'
        cat "$outdir/dns_records.txt" 2>/dev/null || echo "No DNS data"
        echo '```'
        echo
        echo "## Port Scan (Top 1000)"
        echo '```'
        cat "$outdir/nmap_top1000.txt" 2>/dev/null || echo "No nmap data"
        echo '```'
        echo
        echo "## Web Technologies"
        echo '```'
        cat "$outdir/whatweb.txt" 2>/dev/null || echo "No WhatWeb data"
        echo '```'
        echo
        echo "## Directory Enumeration"
        echo '```'
        cat "$outdir/gobuster_dirs.txt" 2>/dev/null || echo "No directory data"
        echo '```'
        echo
        echo "---"
        echo "*Report generated on $(uname -a)*"
    } > "$report"

    success "Markdown report created → $report"
}
